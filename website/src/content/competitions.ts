export function leagueLandingBySlug(slug: string): LeagueLanding | undefined {
  return LEAGUE_LANDINGS.find((l) => l.slug === slug);
}

/** صفحات البطولات بترتيب العرض المعتمد — تتجاهل ما لم تُضف صفحته بعد */
export function leagueLandingsInPageOrder(): LeagueLanding[] {
  return LEAGUE_PAGE_ORDER
    .map((slug) => leagueLandingBySlug(slug))
    .filter((landing): landing is LeagueLanding => Boolean(landing));
}

export function teamLandingBySlug(slug: string): TeamLanding | undefined {
  return TEAM_LANDINGS.find((t) => t.slug === slug);
}

/** كل مسارات صفحات الهبوط — لاستخدامها في البناء والتنقل */
export function landingRoutes(): string[] {
  return [
    ...LEAGUE_LANDINGS.map((l) => `/matches/${l.slug}`),
    ...TEAM_LANDINGS.map((t) => `/world-cup-2026/${t.slug}`),
  ];
}

export interface Broadcaster {
  name: string;
  /** جملة التعريف — بصيغة الإعلان والإحالة، لا بصيغة الملكية */
  detail: string;
  /** رابط رسمي مباشر للجهة (من ملف الوجهات الرسمية فقط) */
  url?: string;
}

export interface FaqItem {
  q: string;
  a: string;
}

export interface LeagueLanding {
  /** السلاج العربي للمسار: /matches/{slug} */
  slug: string;
  /** معرّف البطولة في مصدر البيانات (scoreboard.php) */
  leagueId: string;
  /** الاسم المختصر لعناوين الجداول والبطاقات */
  shortName: string;
  h1: string;
  title: string;
  description: string;
  /** فقرات التعريف — تظهر حرفياً في الصفحة */
  intro: string[];
  broadcasters: Broadcaster[];
  faq: FaqItem[];
  /** سطر التعريف في صورة المشاركة — غيابه يعني القيمة الافتراضية في سكربت الرسم */
  ogSubtitle?: string;
  /**
   * قسم «جدول الترتيب» — يُملأ **فقط** بعد إثبات المصدر بمسبار موثّق يثبت
   * معرّف الدوري وعدد الفرق، وبعد إدراج البطولة في قائمة standings.php
   * المسموحة. `leagueId` هنا معرّف لدى مصدر الترتيب تحديداً، وقد يختلف عن
   * معرّف المباريات (الدوري السعودي مثالاً: sau.1 للمباريات وksa.1 للترتيب).
   */
  standings?: { leagueId: string; provider: 'ESPN' };
  /**
   * نص «غير متاح» لبطولة لم يثبت مصدر ترتيبها بعد — يظهر حرفياً بدل الجدول.
   * لا يُستكمل ترتيب ناقص من موقع آخر ولا يُخمَّن.
   */
  standingsUnavailable?: string;
  /**
   * تاريخ نشر/تحديث هذه الصفحة تحديداً (YYYY-MM-DD) لبيانات منظّمة دقيقة.
   * غيابه يعني الرجوع إلى تاريخ صفحات الهبوط العام — ولا يُغيَّر تاريخ صفحة
   * قائمة بلا تغيّر جوهري في محتواها.
   */
  date?: string;
}


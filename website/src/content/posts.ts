export interface PostImage {
  /** مسار الصورة بلا امتداد ولا مقاس: /images/articles/http-protocols/http-request-cycle */
  base: string;
  alt: string;
  caption?: string;
  width: number;
  height: number;
}

/* كتل المحتوى داخل القسم الواحد — ترتيبها في المصفوفة هو ترتيب ظهورها في الصفحة،
   فالمقال الطويل يحتاج مزج النص مع الكود والصورة بأي تسلسل يريده الكاتب. */
export type PostBlock =
  | { p: string }
  | { code: { lines: string[]; label?: string } }
  | { img: PostImage }
  | { list: string[] }
  | { steps: string[] }
  | { note: string; label?: string }
  | { quote: string }
  | { table: { head: string[]; rows: string[][] } }
  | { related: { label: string; href: string; desc?: string }[] };

export interface PostSection {
  heading?: string;
  /** المحتوى مرتّباً — يُستخدم هذا الحقل في المقالات الجديدة */
  blocks?: PostBlock[];
  /* الحقول التالية تُترجم إلى blocks بنفس ترتيب الرسم القديم،
     حتى تبقى المقالات المنشورة سابقاً كما هي بلا أي تغيير في مخرجاتها. */
  paragraphs?: string[];
  bullets?: string[];
  steps?: string[];
  table?: { head: string[]; rows: string[][] };
  note?: string;
  code?: { lines: string[]; label?: string };
  quote?: string;
  image?: PostImage;
  related?: { label: string; href: string; desc?: string }[];
}

/* تحويل الحقول القديمة إلى قائمة كتل بنفس ترتيب العرض السابق */
export function sectionBlocks(section: PostSection): PostBlock[] {
  if (section.blocks) return section.blocks;
  const out: PostBlock[] = [];
  if (section.quote) out.push({ quote: section.quote });
  section.paragraphs?.forEach((p) => out.push({ p }));
  if (section.code) out.push({ code: section.code });
  if (section.image) out.push({ img: section.image });
  if (section.note) out.push({ note: section.note });
  if (section.bullets) out.push({ list: section.bullets });
  if (section.steps) out.push({ steps: section.steps });
  if (section.table) out.push({ table: section.table });
  if (section.related) out.push({ related: section.related });
  return out;
}


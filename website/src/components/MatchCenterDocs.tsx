import { SUPPORT_EMAIL } from '../config';
import type { MatchDefinition } from '../lib/match-center.mjs';

/* ==========================================================================
   «توثيق ومراجعة» — البيت الوحيد لكل نص عن المصدر وطريقة قراءة الأرقام
   --------------------------------------------------------------------------
   أعلى الصفحة للأرقام فقط. كل جملة كانت متناثرة (شرح الشريط، شرح التشكيلة،
   وقت القراءة، معنى «غير متاح»، نطاق المواجهات ومستوى الفريقين، ما لا يصل
   أصلاً) تعيش هنا وحدها، داخل قسم `.mc-docs` القائم آخر الصفحة. لا يُذكر اسم
   مزوّد في أي بطاقة؛ «المصدر» وحده (البند 12).
========================================================================== */

/** تاريخ آخر مراجعة لتسميات الأرقام ووحداتها مقابل المصدر — يُحدَّث يدوياً مع كل مراجعة. */
export const MATCH_CENTER_LABELS_REVIEWED_ON = '18 أكتوبر 2026';

export interface MatchCenterDocsProps {
  match: MatchDefinition;
  /** وقت آخر قراءة بالعربية (بالثواني)، أو `null` قبل أول قراءة. */
  readAtLabel: string | null;
  /** نص حداثة القراءة كما تقرّره طبقة العقد. */
  freshnessText: string | null;
}

export default function MatchCenterDocs({ match, readAtLabel, freshnessText }: MatchCenterDocsProps) {
  const homeName = match.home.name || match.home.sourceName || 'المضيف';
  const awayName = match.away.name || match.away.sourceName || 'الضيف';
  const subject = encodeURIComponent(`رقم غير مطابق في مركز المباراة: ${homeName} ضد ${awayName}`);
  return (
    <>
      <div className="mc-docs-grid">
        <article className="mc-doc" data-doc="read">
          <h3>المصدر وزمن القراءة</h3>
          <p>
            كل الأرقام والأحداث والتشكيلات من قراءة المصدر نفسها التي يعمل بها الموقع، بلا مزوّد إضافي.
            {readAtLabel
              ? <> آخر قراءة ناجحة: <span className="mc-num">{readAtLabel}</span> بتوقيت القاهرة{freshnessText ? ` (${freshnessText})` : ''}؛</>
              : <> لم تصل قراءة بعد؛</>}
            {' '}تتجدد تلقائياً أثناء المباراة، وزر «تحديث الآن» أعلى الصفحة يطلب قراءة فورية.
          </p>
        </article>
        <article className="mc-doc" data-doc="unavailable">
          <h3>معنى «غير متاح»</h3>
          <p>
            تعني أن المصدر لم يرسل هذا الرقم لهذا الطرف في هذه القراءة. لا نستكمله صفراً، ولا نشتقه من أرقام أخرى
            (مثلاً: «خارج المرمى» لا يُحسب بطرح «على المرمى» من الإجمالي). الصفر المعروض صفر حقيقي من المصدر.
            الشريط تحت كل صف نسبة إلى الأعلى بين الرقمين في الصف نفسه فقط — لا درجة من 100 ولا حكم جودة:
            زيادة الأخطاء أو البطاقات أو التسلل أرقام، ليست أفضلية.
          </p>
        </article>
        <article className="mc-doc" data-doc="absent">
          <h3>ما لا يرسله المصدر أصلاً</h3>
          <p>
            تسديدات خارج المرمى، داخل/خارج المنطقة، الالتحامات الأرضية والهوائية، المراوغات، فقدان الاستحواذ،
            اللمسات داخل المنطقة، الرميات الجانبية، ضربات المرمى، التقاط الكرات العالية، التمريرات البينية،
            تمريرات الثلث الأخير، تقييمات اللاعبين، ونموذج الأهداف المتوقعة. هذه لا تظهر في الصفحة ولا تُمثَّل بأي شكل.
          </p>
        </article>
        <article className="mc-doc" data-doc="timeline">
          <h3>كيف يُقرأ شريط الأحداث</h3>
          <p>
            الشريط الزمني على الملعب يعرض الدقيقة وجهة الفريق فقط؛ الأحداث لا تحمل إحداثيات مكانية.
            شارات اللاعبين — إن توفرت تشكيلة مؤكدة — تربط الحدث بصاحبه لا بموقع حدوثه على أرض الملعب.
            مرّر المؤشر أو اضغط على أي رمز لعرض تفاصيله، والنقر يثبّته.
          </p>
        </article>
        <article className="mc-doc" data-doc="lineups">
          <h3>كيف تُقرأ التشكيلة</h3>
          <p>
            توزيع تخطيطي حسب مراكز المصدر (الرمز اللاتيني تحت اسم اللاعب هو رمز المصدر، والتسمية العربية ترجمتنا له)،
            وليس إحداثيات أو حركة فعلية. تبقى التشكيلة الأساسية ثابتة؛ شارات التبديلات لا تغيّر مواقع اللاعبين،
            والبديل المرتبط بحدث يظهر في صف البدلاء أسفل تشكيلة فريقه. قبل صدور التشكيلة يعرض الملعب المعاينة
            (حقائق المباراة ومستوى الفريقين)، وفور صدورها تحل محلها على الملعب وتنتقل المعاينة إلى تبويب «قبل المباراة».
          </p>
        </article>
        <article className="mc-doc" data-doc="history">
          <h3>المواجهات ومستوى الفريقين</h3>
          <p>
            المواجهات في تبويب «قبل المباراة»: العينة هي آخر 3 مواجهات مكتملة كما أرسلها المصدر عبر البطولات كافة،
            وليست سجلاً تاريخياً كاملاً. سطر المجمل (فوز/تعادل/فوز) يُحسب من الصفوف المعروضة نفسها فقط، ويُخفى إن
            تعذّرت نسبة أي نتيجة لأحد الطرفين. «مستوى الفريقين» يغطي آخر 5 مباريات موثقة لكل فريق عبر البطولات التي
            أرسلها المصدر، ومتوسطاته مقسومة على العدد الفعلي المعروض.
          </p>
        </article>
      </div>
      <p className="mc-docs-review">
        <span><strong>مراجعة</strong> تُراجع تسميات الأرقام ووحداتها مقابل المصدر عند كل تغيير في الموسم؛ آخر مراجعة: {MATCH_CENTER_LABELS_REVIEWED_ON}.</span>
        <a className="mc-report" href={`mailto:${SUPPORT_EMAIL}?subject=${subject}`}>أبلغ عن رقم غير مطابق</a>
      </p>
    </>
  );
}
